const fs=require('node:fs');
const path=require('node:path');
const parts=["tokens", "layout", "buttons", "content", "surfaces", "forms", "disclosure", "navigation", "menus", "overlays", "feedback", "popups", "material", "helpers", "utilities", "motion", "responsive", "grid", "spacing", "variants"];
const root=path.resolve(__dirname,'..');
const css=parts.map(n=>fs.readFileSync(path.join(root,'css/modules',n+'.css'),'utf8')).join('\n');
fs.writeFileSync(path.join(root,'css/gridmaterial.css'),'/* GridMaterial v1.1.0 | generated by npm run build:css | edit css/modules/*.css */\n'+css);
console.log('Built css/gridmaterial.css from '+parts.length+' CSS modules');
